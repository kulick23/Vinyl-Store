create table public.artists (
  id bigint generated by default as identity primary key,
  name text not null unique
);

create table public.genres (
  id bigint generated by default as identity primary key,
  name text not null unique
);

create table public.releases (
  id bigint generated by default as identity primary key,
  external_id bigint,
  title text not null,
  year integer not null check (year between 1000 and 9999),
  artist_id bigint not null references public.artists(id) on delete restrict,
  genre_id bigint not null references public.genres(id) on delete restrict,
  image_url text,
  created_at timestamptz not null default now()
);

create table public.seller_profiles (
  id bigint generated by default as identity primary key,
  user_id uuid unique references auth.users(id) on delete set null,
  display_name text not null,
  description text not null default '',
  rating numeric(3, 2) not null default 0 check (rating between 0 and 5),
  avatar_url text,
  created_at timestamptz not null default now()
);

create table public.inventory_items (
  id bigint generated by default as identity primary key,
  release_id bigint not null references public.releases(id) on delete cascade,
  seller_id bigint not null references public.seller_profiles(id) on delete cascade,
  price numeric(12, 2) not null check (price >= 0),
  quantity integer not null check (quantity >= 0),
  condition smallint not null check (condition between 0 and 5),
  notes text not null default '',
  created_at timestamptz not null default now()
);

create index releases_artist_id_idx on public.releases(artist_id);
create index releases_genre_id_idx on public.releases(genre_id);
create index releases_year_idx on public.releases(year);
create index inventory_items_release_price_idx
  on public.inventory_items(release_id, price);
create index inventory_items_seller_id_idx
  on public.inventory_items(seller_id);

alter table public.artists enable row level security;
alter table public.genres enable row level security;
alter table public.releases enable row level security;
alter table public.seller_profiles enable row level security;
alter table public.inventory_items enable row level security;

revoke all on table public.artists from anon, authenticated;
revoke all on table public.genres from anon, authenticated;
revoke all on table public.releases from anon, authenticated;
revoke all on table public.seller_profiles from anon, authenticated;
revoke all on table public.inventory_items from anon, authenticated;

grant select on table public.artists to anon, authenticated;
grant select on table public.genres to anon, authenticated;
grant select on table public.releases to anon, authenticated;
grant select on table public.seller_profiles to anon, authenticated;
grant select on table public.inventory_items to anon, authenticated;

create policy "Public catalog can read artists"
  on public.artists for select
  to anon, authenticated
  using (true);

create policy "Public catalog can read genres"
  on public.genres for select
  to anon, authenticated
  using (true);

create policy "Public catalog can read releases"
  on public.releases for select
  to anon, authenticated
  using (true);

create policy "Public catalog can read sellers"
  on public.seller_profiles for select
  to anon, authenticated
  using (true);

create policy "Public catalog can read available inventory"
  on public.inventory_items for select
  to anon, authenticated
  using (quantity > 0);

